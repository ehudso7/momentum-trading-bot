def _read_growth_records(path: Path) -> list[dict]:
    if not path.exists():
        return []
    try:
        raw = path.read_text(encoding="utf-8")
    except Exception:
        return []
    out: list[dict] = []
    for line in raw.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        try:
            parsed = json.loads(stripped)
        except Exception:
            continue
        if isinstance(parsed, dict):
            out.append(parsed)
    return out


def summarize(
    path: Optional[Union[str, Path]] = None,
    *,
    limit: Optional[int] = None,
) -> dict:
    """
    Aggregate the growth log into a ref-level summary.

    Returns a dict of the form::

        {
            "total_events": 42,
            "distinct_refs": 5,
            "distinct_users": 27,
            "refs": [
                {"ref_code": "hn_launch",  "events": 12, "unique_users": 8, "paths": 3},
                ...
            ],
        }

    ``refs`` is sorted by event count descending. ``limit`` caps the
    number of ref rows returned (top-N).
    """
    target = Path(path) if path is not None else _growth_log_path()
    records = _read_growth_records(target)

    per_ref_events: dict[str, int] = defaultdict(int)
    per_ref_users: dict[str, set[str]] = defaultdict(set)
    per_ref_paths: dict[str, set[str]] = defaultdict(set)
    distinct_users_total: set[str] = set()

    for rec in records:
        ref = rec.get("ref_code")
        if not ref:
            continue
        ref = str(ref)
        per_ref_events[ref] += 1
        h = rec.get("api_key_hash")
        if h:
            per_ref_users[ref].add(str(h))
            distinct_users_total.add(str(h))
        rpath = rec.get("path")
        if rpath:
            per_ref_paths[ref].add(str(rpath))

    refs_list = [
        {
            "ref_code": ref,
            "events": per_ref_events[ref],
            "unique_users": len(per_ref_users[ref]),
            "paths": len(per_ref_paths[ref]),
        }
        for ref in per_ref_events
    ]
    refs_list.sort(
        key=lambda r: (r["events"], r["unique_users"]),
        reverse=True,
    )
    if limit is not None and limit > 0:
        refs_list = refs_list[:limit]

    return {
        "total_events": len(records),
        "distinct_refs": len(per_ref_events),
        "distinct_users": len(distinct_users_total),
        "refs": refs_list,
    }


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m trading_bot.api.growth",
        description=(
            "Summarize the growth-loop log (ref-code usage per "
            "distinct user)."
        ),
    )
    parser.add_argument(
        "--summary", action="store_true",
        help="Print a ref-code summary to stdout",
    )
    parser.add_argument(
        "--path", default=None,
        help=(
            "Path to the growth JSONL file "
            f"(default: ${GROWTH_LOG_ENV_VAR} or {DEFAULT_GROWTH_LOG_PATH})"
        ),
    )
    parser.add_argument(
        "--json", action="store_true",
        help="Emit JSON instead of human-readable text",
    )
    parser.add_argument(
        "--top", type=int, default=None,
        help="Limit to the top N ref codes",
    )
    return parser


def _format_summary_text(summary: dict) -> str:
    lines: list[str] = []
    lines.append(
        f"Total growth events    = {summary.get('total_events', 0)}"
    )
    lines.append(
        f"Distinct ref codes     = {summary.get('distinct_refs', 0)}"
    )
    lines.append(
        f"Distinct unique users  = {summary.get('distinct_users', 0)}"
    )
    refs = summary.get("refs") or []
    if not refs:
        lines.append("")
        lines.append("(no ref-code activity recorded)")
        return "\n".join(lines)
    lines.append("")
    header = f"  {'ref_code':<32} {'events':>8} {'unique_users':>13} {'paths':>7}"
    lines.append(header)
    lines.append("  " + "-" * (len(header) - 2))
    for row in refs:
        lines.append(
            f"  {str(row['ref_code'])[:32]:<32} "
            f"{row['events']:>8} "
            f"{row['unique_users']:>13} "
            f"{row['paths']:>7}"
        )
    return "\n".join(lines)


def main(argv: Optional[list[str]] = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)

    if not args.summary:
        parser.print_help(sys.stderr)
        return 2

    summary = summarize(
        path=args.path,
        limit=args.top if args.top and args.top > 0 else None,
    )

    if args.json:
        print(json.dumps(summary, indent=2, sort_keys=False, default=str))
    else:
        print(_format_summary_text(summary))
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
