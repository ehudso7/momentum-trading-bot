"""
Phase 5.1 — Growth loop tracking.

Records one JSONL event each time an authenticated caller hits an
endpoint with a ``?ref=<code>`` query parameter. The goal is to
identify which referral / distribution sources actually drive
active users (not just pageviews), without storing any personal
data at all.

Privacy posture (identical to the Phase 4.9 conversion log):
  * Raw API keys are **never** persisted. Only
    ``SHA-256(api_key)[:32]``, which matches the
    ``_hash_api_key`` digest used by server / billing / conversion
    so BI pipelines can join the four files on one column.
  * No IP, no User-Agent, no email, no name, no card data ever
    enters a record — the only inputs are the opaque api-key
    hash, the caller-supplied ref_code, the HTTP path, and the
    request_id generated by Phase 4.4.
  * A leak-guard test plants unique-marker strings in the raw
    inputs and asserts they never appear in the growth file.

Failure posture:
  * All I/O is best-effort — a disk failure never breaks the
    underlying API request.
  * Thread-safe via a module-level ``threading.Lock``.
  * Dedup by ``(api_key_hash, ref_code)`` within a sliding 24h
    window — a chatty client that reloads the same ``?ref=``
    URL repeatedly is counted once.

Env vars:
    TRADING_API_GROWTH_LOG_PATH   JSONL output path
                                  (default: data/api_growth.jsonl)

CLI:
    python -m trading_bot.api.growth --summary
    python -m trading_bot.api.growth --summary --json
    python -m trading_bot.api.growth --summary --path path/to.jsonl
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import threading
from collections import defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Optional, Union

import structlog

log = structlog.get_logger(__name__)


# ---------------------------------------------------------------------------
# Config + module state
# ---------------------------------------------------------------------------

GROWTH_LOG_ENV_VAR = "TRADING_API_GROWTH_LOG_PATH"
DEFAULT_GROWTH_LOG_PATH = "data/api_growth.jsonl"

DEDUP_WINDOW_HOURS = 24
DEDUP_WINDOW_SECONDS = DEDUP_WINDOW_HOURS * 60 * 60

# ref_code sanitisation. Accept alnum, -, _, :, . and cap length.
REF_CODE_MAX_LENGTH = 64
import re  # noqa: E402
_REF_CODE_STRIP_RE = re.compile(r"[^A-Za-z0-9\-_:.]")

# In-memory dedup cache: {(api_key_hash, ref_code): last_event_utc}.
# Rehydrated lazily from disk so dedup survives a process restart.
_dedup_cache: dict[tuple[str, str], datetime] = {}
_dedup_loaded_from: Optional[Path] = None
_write_lock = threading.Lock()


# ---------------------------------------------------------------------------
# Pure helpers
# ---------------------------------------------------------------------------


def _hash_api_key(api_key: Optional[str]) -> str:
    """SHA-256[:32] — identical to server/billing/conversion hashers."""
    if not api_key:
        return ""
    return hashlib.sha256(str(api_key).encode("utf-8")).hexdigest()[:32]


def _growth_log_path() -> Path:
    return Path(
        os.getenv(GROWTH_LOG_ENV_VAR, DEFAULT_GROWTH_LOG_PATH)
    )


def _sanitize_ref_code(raw: Optional[str]) -> str:
    """
    Strip to the documented safe character set, cap length. Untrusted
    input — a caller can put anything in a query param.
    """
    if raw is None:
        return ""
    s = str(raw)
    if not s:
        return ""
    cleaned = _REF_CODE_STRIP_RE.sub("", s)[:REF_CODE_MAX_LENGTH]
    return cleaned


def _parse_iso_utc(ts: Optional[str]) -> Optional[datetime]:
    if ts is None:
        return None
    s = str(ts).strip()
    if not s:
        return None
    try:
        if s.endswith("Z"):
            s = s[:-1] + "+00:00"
        dt = datetime.fromisoformat(s)
    except Exception:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt


def _load_dedup_cache(
    path: Path,
    *,
    now: datetime,
    window_seconds: int = DEDUP_WINDOW_SECONDS,
) -> dict[tuple[str, str], datetime]:
    """
    Rebuild the dedup set from any existing on-disk records whose
    timestamps fall inside the window. Corrupt / malformed lines
    are silently skipped.
    """
    if not path.exists():
        return {}
    out: dict[tuple[str, str], datetime] = {}
    threshold = now - timedelta(seconds=window_seconds)
    try:
        raw = path.read_text(encoding="utf-8")
    except Exception:
        return {}
    for line in raw.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        try:
            rec = json.loads(stripped)
        except Exception:
            continue
        if not isinstance(rec, dict):
            continue
        ts = _parse_iso_utc(rec.get("timestamp"))
        if ts is None or ts < threshold:
            continue
        h = rec.get("api_key_hash")
        ref = rec.get("ref_code")
        if not (h and ref):
            continue
        key = (str(h), str(ref))
        prev = out.get(key)
        if prev is None or ts > prev:
            out[key] = ts
    return out


def _ensure_dedup_loaded() -> None:
    """Rehydrate the dedup cache if the configured path has changed."""
    global _dedup_loaded_from
    path = _growth_log_path()
    with _write_lock:
        if _dedup_loaded_from != path:
            _dedup_cache.clear()
            _dedup_cache.update(
                _load_dedup_cache(
                    path, now=datetime.now(timezone.utc),
                )
            )
            _dedup_loaded_from = path


def reset_cache_for_tests() -> None:
    """Test helper — clear the in-memory dedup cache + path pointer."""
    global _dedup_loaded_from
    with _write_lock:
        _dedup_cache.clear()
        _dedup_loaded_from = None


def _append_growth_record(
    record: dict,
    path: Optional[Path] = None,
) -> None:
    """Best-effort append. Never raises."""
    target = path if path is not None else _growth_log_path()
    try:
        line = json.dumps(record, sort_keys=False, default=str)
    except Exception as exc:
        log.debug("growth.serialize_error", error=str(exc))
        return
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except Exception as exc:
        log.debug("growth.write_error", path=str(target), error=str(exc))


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def record_growth_event(
    *,
    api_key: Optional[str],
    ref_code: Optional[str],
    path: Optional[str] = None,
    request_id: Optional[str] = None,
    now: Optional[datetime] = None,
) -> dict:
    """
    Record a growth event. Returns a small diagnostics dict:

      - ``{"action": "recorded", "api_key_hash": "...", "ref_code": "..."}``
      - ``{"action": "deduped",  ...}`` — same pair within 24h.
      - ``{"action": "skipped",  "reason": ...}`` — empty/invalid input.

    Dedup is by ``(api_key_hash, ref_code)`` within
    ``DEDUP_WINDOW_HOURS`` (24). A 25-hour-old duplicate will record
    again (makes sense — we do want to see which refs keep driving
    return usage over time).

    Never raises. Failure to write simply logs at DEBUG and moves
    on; the dedup cache is still updated so the API caller cannot
    hammer the same URL and generate a flood of near-duplicate
    rows on a retry.
    """
    hashed = _hash_api_key(api_key)
    if not hashed:
        return {"action": "skipped", "reason": "no_api_key"}
    cleaned = _sanitize_ref_code(ref_code)
    if not cleaned:
        return {"action": "skipped", "reason": "no_ref_code"}

    current = now if now is not None else datetime.now(timezone.utc)
    if current.tzinfo is None:
        current = current.replace(tzinfo=timezone.utc)

    _ensure_dedup_loaded()
    dedup_key = (hashed, cleaned)
    with _write_lock:
        previous = _dedup_cache.get(dedup_key)
        if previous is not None:
            if previous.tzinfo is None:
                previous = previous.replace(tzinfo=timezone.utc)
            if (current - previous).total_seconds() < DEDUP_WINDOW_SECONDS:
                return {
                    "action": "deduped",
                    "api_key_hash": hashed,
                    "ref_code": cleaned,
                }
        # Reserve the slot under the lock BEFORE we release it — this
        # prevents two concurrent callers from both writing a row for
        # the same (hash, ref) pair within the window.
        _dedup_cache[dedup_key] = current

    record = {
        "timestamp": current.strftime("%Y-%m-%dT%H:%M:%S.%fZ"),
        "api_key_hash": hashed,
        "ref_code": cleaned,
        "path": str(path) if path else "",
        "request_id": str(request_id) if request_id else None,
    }
    _append_growth_record(record)
    return {
        "action": "recorded",
        "api_key_hash": hashed,
        "ref_code": cleaned,
    }


